<?php
// Render the platform's part of Moodle's configuration from the environment.
//
// Runs on every container start (after the lifecycle validated the variables),
// so a changed DB_* or MOODLE_WWWROOT takes effect on the next restart and
// nothing else has to rewrite config.php. Values go through var_export, so a
// password with quotes or a backslash cannot break out of the string.
//
// Everything set here is LOCKED in Moodle's admin UI (Moodle shows settings
// defined in config.php as fixed). That is the point for infrastructure — a
// site admin must not be able to repoint the database or the Ghostscript path
// — and the reason nothing that belongs to the site (SMTP, themes, …) is here.
//
// Usage: php render-config.php OUTPUT_FILE

declare(strict_types=1);

if ($argc !== 2) {
    fwrite(STDERR, "usage: render-config.php OUTPUT_FILE\n");
    exit(2);
}

function env(string $name, ?string $default = null): ?string {
    $v = getenv($name);
    return ($v === false || $v === '') ? $default : $v;
}

$root = env('MOODLE_ROOT', '/var/www/moodle');
$dbtype = env('DB_TYPE', 'mariadb');
$wwwroot = rtrim((string) env('MOODLE_WWWROOT'), '/');

$set = [];   // $CFG->name = value, always
$lines = [];

$set['dbtype'] = $dbtype;
$set['dblibrary'] = 'native';
$set['dbhost'] = env('DB_HOST');
$set['dbname'] = env('DB_NAME');
$set['dbuser'] = env('DB_USER');
$set['dbpass'] = env('DB_PASSWORD');
$set['prefix'] = env('DB_PREFIX', 'mdl_');
$dboptions = [
    'dbpersist' => 0,
    'dbport' => (int) env('DB_PORT', $dbtype === 'pgsql' ? '5432' : '3306'),
    'dbsocket' => '',
];
if ($dbtype !== 'pgsql') {
    $dboptions['dbcollation'] = env('DB_COLLATION', 'utf8mb4_unicode_ci');
}
$set['dboptions'] = $dboptions;

$set['wwwroot'] = $wwwroot;
$set['dataroot'] = $root . '/moodledata';
$set['admin'] = 'admin';

// TLS ends at the platform's ingress; the request reaching Apache is plain
// HTTP. sslproxy tells Moodle the public URL is https anyway. NOT reverseproxy:
// that is for a site reached under a different URL than its wwwroot.
$set['sslproxy'] = str_starts_with($wwwroot, 'https://');

// Apache sends every request for a file that does not exist to r.php
// (FallbackResource in moodle.conf), which is what this flag asserts.
$set['routerconfigured'] = true;

// Rebuilt from scratch by Moodle whenever it is missing, so it can live on the
// container's own disk instead of the network volume: faster, and never stale
// after a code swap.
$set['localcachedir'] = '/var/cache/insula-moodle/localcache';

// The executables this image ships, at fixed paths. preventexecpath stops a
// site admin from pointing one of them at any other binary on the server —
// which would otherwise run it as the web server user.
$set['preventexecpath'] = true;
$set['pathtogs'] = '/usr/bin/gs';
$set['pathtopdftoppm'] = '/usr/bin/pdftoppm';
$set['pathtounoconv'] = '/usr/bin/unoconv';
$set['pathtodot'] = '/usr/bin/dot';
$set['pathtodu'] = '/usr/bin/du';
$set['pathtopython'] = '/usr/bin/python3';
$set['aspellpath'] = '/usr/bin/aspell';

// Debug messages still go to the PHP error log (the pod log). Shown in pages,
// they end up inside JSON responses and break the assignment grader and other
// AJAX pages with "Unexpected token '<'".
$set['debugdisplay'] = 0;

// BigBlueButton: pinned only when both variables are set. Pinned, the admin
// page shows them as defined in config.php and cannot change them, so nobody
// queues reset_recordings by editing the URL, and the secret is not stored in
// the database or its backups.
$bbburl = env('MOODLE_BBB_SERVER_URL');
$bbbsecret = env('MOODLE_BBB_SHARED_SECRET');
if ($bbburl !== null && $bbbsecret !== null) {
    $set['bigbluebuttonbn_server_url'] = $bbburl;
    $set['bigbluebuttonbn_shared_secret'] = $bbbsecret;
}

$out = "<?php\n"
    . "// Generated by insula-moodle from the deployment's environment on every\n"
    . "// container start. Do not edit: change the deployment's settings instead.\n"
    . "// Put site-specific settings in config-local.php next to moodledata/.\n\n";
foreach ($set as $name => $value) {
    $out .= '$CFG->' . $name . ' = ' . var_export($value, true) . ";\n";
}

// BigBlueButton's own task schedules hammer the server (see the bundled
// local_bbbrecordingsync plugin's README). A schedule the site already set in
// config-local.php wins over these.
$out .= "\n\$CFG->scheduled_tasks = (\$CFG->scheduled_tasks ?? []) + " . var_export([
    // Upstream runs this every minute of every 10th day.
    '\\mod_bigbluebuttonbn\\task\\check_dismissed_recordings' => ['schedule' => '17 3 */10 * *'],
    // Every 15 minutes instead of 5: a new recording may take up to 15 minutes to appear.
    '\\mod_bigbluebuttonbn\\task\\check_pending_recordings' => ['schedule' => '*/15 * * * *'],
], true) . ";\n";

$tmp = $argv[1] . '.tmp';
if (file_put_contents($tmp, $out) === false) {
    fwrite(STDERR, "cannot write $tmp\n");
    exit(1);
}
chmod($tmp, 0640);
rename($tmp, $argv[1]);
